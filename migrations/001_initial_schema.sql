-- Function to automatically set updated_at timestamp
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 1. USER PROFILES & RBAC
CREATE TABLE IF NOT EXISTS public.user_profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_user_id UUID,
  username TEXT UNIQUE NOT NULL,
  email TEXT UNIQUE NOT NULL,
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('owner', 'super_admin', 'admin', 'editor', 'user')),
  permissions JSONB DEFAULT '{}'::jsonb,
  avatar_url TEXT DEFAULT 'sasi_profile.jpg',
  status TEXT DEFAULT 'active' CHECK (status IN ('active', 'suspended', 'inactive')),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  last_login TIMESTAMPTZ
);

CREATE TRIGGER trg_user_profiles_updated
BEFORE UPDATE ON public.user_profiles
FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

-- 2. PORTFOLIO SETTINGS (Key-Value configuration with categories and public flags)
CREATE TABLE IF NOT EXISTS public.portfolio_settings (
  key TEXT PRIMARY KEY,
  value TEXT,
  category TEXT DEFAULT 'general',
  is_public BOOLEAN DEFAULT TRUE,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. THEMES (Draft & Published Themes with Full Typography, Radii and Custom CSS)
CREATE TABLE IF NOT EXISTS public.themes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  is_draft BOOLEAN DEFAULT FALSE,
  primary_color TEXT DEFAULT '#00D9C0',
  secondary_color TEXT DEFAULT '#FF5A5F',
  accent_color TEXT DEFAULT '#F59E0B',
  bg_dark TEXT DEFAULT '#0B0E14',
  bg_card TEXT DEFAULT '#151B28',
  text_main TEXT DEFAULT '#F8FAFC',
  text_muted TEXT DEFAULT '#94A3B8',
  font_family TEXT DEFAULT 'Space Grotesk',
  font_size_base TEXT DEFAULT '16px',
  border_radius TEXT DEFAULT '16px',
  button_radius TEXT DEFAULT '8px',
  hero_overlay_opacity NUMERIC DEFAULT 0.72,
  hero_overlay_blur NUMERIC DEFAULT 2,
  animation_speed TEXT DEFAULT 'normal',
  theme_mode TEXT DEFAULT 'dark',
  custom_css TEXT DEFAULT '',
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TRIGGER trg_themes_updated
BEFORE UPDATE ON public.themes
FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

-- 4. WEBSITE SECTIONS (Hero, About, Videos, Services, Gallery, Contact, etc.)
CREATE TABLE IF NOT EXISTS public.sections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section_id TEXT UNIQUE NOT NULL,
  title TEXT NOT NULL,
  title_ta TEXT DEFAULT '',
  subtitle TEXT DEFAULT '',
  subtitle_ta TEXT DEFAULT '',
  content_json JSONB DEFAULT '{}'::jsonb,
  is_visible BOOLEAN DEFAULT TRUE,
  sort_order INT DEFAULT 0,
  background_type TEXT DEFAULT 'color',
  background_value TEXT DEFAULT '#07090E',
  custom_css TEXT DEFAULT '',
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TRIGGER trg_sections_updated
BEFORE UPDATE ON public.sections
FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

-- 5. PROJECT CATEGORIES
CREATE TABLE IF NOT EXISTS public.project_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT UNIQUE NOT NULL,
  slug TEXT UNIQUE NOT NULL,
  description TEXT DEFAULT ''
);

-- 6. PORTFOLIO PROJECTS / CONTENT
CREATE TABLE IF NOT EXISTS public.portfolio_projects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  title_ta TEXT DEFAULT '',
  slug TEXT UNIQUE NOT NULL,
  excerpt TEXT DEFAULT '',
  excerpt_ta TEXT DEFAULT '',
  content TEXT DEFAULT '',
  content_ta TEXT DEFAULT '',
  category TEXT DEFAULT 'Event Aftermovie',
  tags TEXT DEFAULT '',
  media_url TEXT DEFAULT '',
  media_type TEXT DEFAULT 'video',
  thumbnail_url TEXT DEFAULT '',
  status TEXT DEFAULT 'published' CHECK (status IN ('draft', 'published', 'archived')),
  views INT DEFAULT 0,
  author_id BIGINT REFERENCES public.user_profiles(id) ON DELETE SET NULL,
  author_name TEXT DEFAULT 'Sasikumar',
  sort_order INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_projects_status ON public.portfolio_projects(status);
CREATE INDEX IF NOT EXISTS idx_projects_category ON public.portfolio_projects(category);
CREATE INDEX IF NOT EXISTS idx_projects_slug ON public.portfolio_projects(slug);

CREATE TRIGGER trg_projects_updated
BEFORE UPDATE ON public.portfolio_projects
FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

-- 7. MEDIA ASSETS LIBRARY
CREATE TABLE IF NOT EXISTS public.media_library (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  original_name TEXT NOT NULL,
  file_path TEXT NOT NULL,
  file_url TEXT NOT NULL,
  media_type TEXT DEFAULT 'image',
  mime_type TEXT DEFAULT 'image/jpeg',
  file_size BIGINT DEFAULT 1048576,
  category TEXT DEFAULT 'General',
  tags TEXT DEFAULT '',
  uploaded_by TEXT DEFAULT 'owner',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_media_category ON public.media_library(category);
CREATE INDEX IF NOT EXISTS idx_media_type ON public.media_library(media_type);

-- 8. CONTACT INQUIRIES & MESSAGES
CREATE TABLE IF NOT EXISTS public.contact_inquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT DEFAULT '',
  subject TEXT DEFAULT '',
  message TEXT NOT NULL,
  status TEXT DEFAULT 'unread' CHECK (status IN ('unread', 'read', 'archived', 'replied')),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_inquiries_status ON public.contact_inquiries(status);

-- 9. ACTIVITY & AUDIT LOGS
CREATE TABLE IF NOT EXISTS public.activity_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.user_profiles(id) ON DELETE SET NULL,
  username TEXT DEFAULT 'system',
  role TEXT DEFAULT 'system',
  action TEXT NOT NULL,
  details TEXT DEFAULT '',
  ip TEXT DEFAULT '127.0.0.1',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_logs_created_at ON public.activity_logs(created_at DESC);

-- 10. PUBLISHING HISTORY & AUDIT TRAIL
CREATE TABLE IF NOT EXISTS public.publishing_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type TEXT NOT NULL,
  entity_id TEXT NOT NULL,
  version INT DEFAULT 1,
  published_by TEXT DEFAULT 'owner',
  data_snapshot JSONB NOT NULL,
  published_at TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================================
-- BACKWARD-COMPATIBILITY VIEWS FOR LEGACY TABLE NAMES
-- ============================================================================
CREATE OR REPLACE VIEW public.content AS SELECT * FROM public.portfolio_projects;
CREATE OR REPLACE VIEW public.media AS SELECT * FROM public.media_library;
CREATE OR REPLACE VIEW public.contact_messages AS SELECT * FROM public.contact_inquiries;
