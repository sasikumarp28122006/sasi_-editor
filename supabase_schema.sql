-- ============================================================================
-- SASI PORTFOLIO — SUPABASE REAL-TIME DATABASE SCHEMA
-- Run this script in the Supabase Dashboard -> SQL Editor -> New Query
-- ============================================================================

-- 1. Portfolio Settings Table (Stores all Website Branding, About, Hero, Theme info)
CREATE TABLE IF NOT EXISTS public.portfolio_settings (
  key TEXT PRIMARY KEY,
  value TEXT,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Website Sections & Layout Table
CREATE TABLE IF NOT EXISTS public.sections (
  id TEXT PRIMARY KEY,
  title TEXT,
  subtitle TEXT,
  sort_order INT DEFAULT 0,
  is_visible BOOLEAN DEFAULT TRUE,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Media Assets Library (Photos, Videos, Thumbnails)
CREATE TABLE IF NOT EXISTS public.media (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  url TEXT NOT NULL,
  media_type TEXT DEFAULT 'image',
  category TEXT DEFAULT 'General',
  size_bytes BIGINT DEFAULT 1048576,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Projects & Showcase Content
CREATE TABLE IF NOT EXISTS public.content (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  slug TEXT,
  category TEXT DEFAULT 'Event Aftermovie',
  excerpt TEXT,
  content TEXT,
  media_url TEXT,
  media_type TEXT DEFAULT 'video',
  thumbnail_url TEXT,
  tags TEXT,
  status TEXT DEFAULT 'published',
  views INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Client Inquiries & Contact Messages
CREATE TABLE IF NOT EXISTS public.contact_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  subject TEXT,
  message TEXT NOT NULL,
  status TEXT DEFAULT 'unread',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================================
-- ENABLE ROW LEVEL SECURITY (RLS) & ALLOW PUBLIC ACCESS WITH PUBLISHABLE KEY
-- ============================================================================
ALTER TABLE public.portfolio_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sections ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.media ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.content ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contact_messages ENABLE ROW LEVEL SECURITY;

-- Allow reading
CREATE POLICY "Allow public read portfolio_settings" ON public.portfolio_settings FOR SELECT USING (true);
CREATE POLICY "Allow public read sections" ON public.sections FOR SELECT USING (true);
CREATE POLICY "Allow public read media" ON public.media FOR SELECT USING (true);
CREATE POLICY "Allow public read content" ON public.content FOR SELECT USING (true);
CREATE POLICY "Allow public read contact_messages" ON public.contact_messages FOR SELECT USING (true);

-- Allow inserting & updating
CREATE POLICY "Allow public insert portfolio_settings" ON public.portfolio_settings FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update portfolio_settings" ON public.portfolio_settings FOR UPDATE USING (true);
CREATE POLICY "Allow public delete portfolio_settings" ON public.portfolio_settings FOR DELETE USING (true);

CREATE POLICY "Allow public insert sections" ON public.sections FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update sections" ON public.sections FOR UPDATE USING (true);
CREATE POLICY "Allow public delete sections" ON public.sections FOR DELETE USING (true);

CREATE POLICY "Allow public insert media" ON public.media FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update media" ON public.media FOR UPDATE USING (true);
CREATE POLICY "Allow public delete media" ON public.media FOR DELETE USING (true);

CREATE POLICY "Allow public insert content" ON public.content FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update content" ON public.content FOR UPDATE USING (true);
CREATE POLICY "Allow public delete content" ON public.content FOR DELETE USING (true);

CREATE POLICY "Allow public insert contact_messages" ON public.contact_messages FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update contact_messages" ON public.contact_messages FOR UPDATE USING (true);
CREATE POLICY "Allow public delete contact_messages" ON public.contact_messages FOR DELETE USING (true);

-- ============================================================================
-- ENABLE SUPABASE REALTIME REPLICATION FOR LIVE UPDATES
-- ============================================================================
ALTER PUBLICATION supabase_realtime ADD TABLE public.portfolio_settings;
ALTER PUBLICATION supabase_realtime ADD TABLE public.sections;
ALTER PUBLICATION supabase_realtime ADD TABLE public.media;
ALTER PUBLICATION supabase_realtime ADD TABLE public.content;

